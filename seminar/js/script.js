// Identifikasi Diri Switchable Tabs Logic
function switchIdentifikasiTab(tabKey) {
    const tabBtnIndo = document.getElementById('tabBtnVisiIndo');
    const tabBtnGuru = document.getElementById('tabBtnVisiGuru');
    const tabBtnStrategi = document.getElementById('tabBtnStrategi');
    const contentBox = document.getElementById('identifikasiTabContent');
    const data = identifikasiData[tabKey];

    if (!data) return;

    const activeStyle = "bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-sm border border-slate-200/60 dark:border-slate-700/50";
    const inactiveStyle = "text-slate-500 hover:text-slate-800 dark:hover:text-slate-200 border border-transparent";

    if (tabBtnIndo) tabBtnIndo.className = `flex-1 py-2.5 px-3 rounded-xl text-xs font-semibold flex items-center justify-center gap-2 transition-all ${tabKey === 'visi_indo' ? activeStyle : inactiveStyle}`;
    if (tabBtnGuru) tabBtnGuru.className = `flex-1 py-2.5 px-3 rounded-xl text-xs font-semibold flex items-center justify-center gap-2 transition-all ${tabKey === 'visi_guru' ? activeStyle : inactiveStyle}`;
    if (tabBtnStrategi) tabBtnStrategi.className = `flex-1 py-2.5 px-3 rounded-xl text-xs font-semibold flex items-center justify-center gap-2 transition-all ${tabKey === 'strategi' ? activeStyle : inactiveStyle}`;

    if (contentBox) {
        contentBox.innerHTML = `
            <div class="space-y-3 w-full">
                <div class="flex items-center gap-2 ${data.colorClass} font-bold text-sm border-b border-slate-200 dark:border-slate-700/60 pb-2">
                    <h4>${data.title}</h4>
                </div>
                <div>${data.content}</div>
            </div>
        `;
    }

    lucide.createIcons();
}

// Horizontal Scroll Controls for Carousel
function scrollCarousel(containerId, direction) {
    const container = document.getElementById(containerId);
    if (container) {
        container.scrollBy({
            left: direction * 340,
            behavior: 'smooth'
        });
    }
}

// Modal Variables & Functions
let activeModalCourse = null;
let activeTabType = 'refleksi';

function findCourseData(id) {
    if (id === 'overall_ppg') return courseDatabase.overall_ppg;
    if (id === 'karya_inovasi') return courseDatabase.karya_inovasi;
    return courseDatabase.sem1.find(c => c.id === id) || courseDatabase.sem2.find(c => c.id === id);
}

function openModalTab(courseId, initialTab = 'refleksi') {
    activeModalCourse = findCourseData(courseId);
    if (!activeModalCourse) return;

    document.getElementById('modalCourseTitle').innerText = activeModalCourse.title;
    document.getElementById('modalCourseSubtitle').innerText = activeModalCourse.subtitle;

    const artBtn = document.getElementById('tabBtnArtefak');
    const labelRefleksi = document.getElementById('tabRefleksiLabel');

    if (activeModalCourse.singleTabOnly) {
        if (artBtn) artBtn.style.display = 'none';
        if (labelRefleksi) labelRefleksi.innerText = "Pratinjau Dokumen";
    } else {
        if (artBtn) artBtn.style.display = 'flex';
        if (labelRefleksi) labelRefleksi.innerText = "Pratinjau Dokumen Refleksi";
    }

    switchModalTab(initialTab);
    document.getElementById('documentModal').classList.remove('hidden');
    lucide.createIcons();
}

function switchModalTab(tabType) {
    activeTabType = tabType;
    const refBtn = document.getElementById('tabBtnRefleksi');
    const artBtn = document.getElementById('tabBtnArtefak');
    const iframe = document.getElementById('modalDocumentIframe');
    const downloadBtn = document.getElementById('modalDownloadBtn');
    const notice = document.getElementById('modalFileNotice');

    if (!activeModalCourse) return;

    if (tabType === 'refleksi') {
        if (refBtn) refBtn.className = "flex-1 py-2.5 rounded-lg text-xs font-semibold flex items-center justify-center gap-2 bg-white dark:bg-slate-900 text-sky-600 dark:text-sky-400 shadow-sm transition-all";
        if (artBtn) artBtn.className = "flex-1 py-2.5 rounded-lg text-xs font-semibold flex items-center justify-center gap-2 text-slate-500 hover:text-slate-800 dark:hover:text-slate-200 transition-all";

        if (iframe) iframe.src = activeModalCourse.refleksiEmbed || "about:blank";
        if (downloadBtn) downloadBtn.href = activeModalCourse.refleksiDownload ? `#download-${activeModalCourse.refleksiDownload}` : '#';
        if (notice) notice.innerText = activeModalCourse.singleTabOnly ? "Pratinjau Dokumen" : `Pratinjau Dokumen Refleksi: ${activeModalCourse.refleksiDownload || ''}`;

    } else {
        if (artBtn) artBtn.className = "flex-1 py-2.5 rounded-lg text-xs font-semibold flex items-center justify-center gap-2 bg-white dark:bg-slate-900 text-emerald-600 dark:text-emerald-400 shadow-sm transition-all";
        if (refBtn) refBtn.className = "flex-1 py-2.5 rounded-lg text-xs font-semibold flex items-center justify-center gap-2 text-slate-500 hover:text-slate-800 dark:hover:text-slate-200 transition-all";

        if (iframe) iframe.src = activeModalCourse.artefakEmbed || "about:blank";
        if (downloadBtn) downloadBtn.href = activeModalCourse.artefakDownload ? `#download-${activeModalCourse.artefakDownload}` : '#';
        if (notice) notice.innerText = `Pratinjau Dokumen Artefak: ${activeModalCourse.artefakDownload || ''}`;
    }

    lucide.createIcons();
}

function closeModal() {
    const iframe = document.getElementById('modalDocumentIframe');
    if (iframe) iframe.src = "about:blank";
    const modal = document.getElementById('documentModal');
    if (modal) modal.classList.add('hidden');
}

// Theme Toggle & Event Listeners
document.addEventListener('DOMContentLoaded', () => {
    const mobileBtn = document.getElementById('mobileMenuBtn');
    if (mobileBtn) mobileBtn.addEventListener('click', toggleMobileMenu);

    const themeToggleBtn = document.getElementById('themeToggle');
    if (themeToggleBtn) {
        if (localStorage.getItem('theme') === 'dark' || (!('theme' in localStorage) && window.matchMedia('(prefers-color-scheme: dark)').matches)) {
            document.documentElement.classList.add('dark');
        } else {
            document.documentElement.classList.remove('dark');
        }

        themeToggleBtn.addEventListener('click', () => {
            if (document.documentElement.classList.contains('dark')) {
                document.documentElement.classList.remove('dark');
                localStorage.setItem('theme', 'light');
            } else {
                document.documentElement.classList.add('dark');
                localStorage.setItem('theme', 'dark');
            }
        });
    }

    renderCarousels();
    switchIdentifikasiTab('visi_indo');
});
